export function buildFallbackHeatmap(): HeatmapData {
  const cells = [];
  const today = new Date();
  today.setHours(0, 0, 0, 0);
  for (let i = 83; i >= 0; i -= 1) {
    const day = new Date(today);
    day.setDate(today.getDate() - i);
    const ordinal = Math.floor(day.getTime() / 86400000);
    let count = (ordinal * 17 + (day.getMonth() + 1) * 3) % 11;
    if (day.getDay() === 0 || day.getDay() === 6) count = Math.floor(count / 3);
    let level = 0;
    if (count <= 0) level = 0;
    else if (count <= 2) level = 1;
    else if (count <= 4) level = 2;
    else if (count <= 7) level = 3;
    else level = 4;
    cells.push({ date: day.toISOString().slice(0, 10), count, level });
  }
  return {
    cells,
    max_count: Math.max(...cells.map((c) => c.count)),
    total_findings_period: cells.reduce((sum, c) => sum + c.count, 0),
    weeks: 12,
  };
}

